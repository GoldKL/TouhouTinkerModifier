import slimeknights.tconstruct.library.tools.nbt.IToolStackView;

public class AuroraofmeltdreamMeleeModifier extends Modifier implements MeleeHitModifierHook {
    @Override
    protected void registerHooks(ModuleHookMap.Builder hookBuilder) {
        super.registerHooks(hookBuilder);
        hookBuilder.addHook(this, ModifierHooks.MELEE_HIT);
    }

    @Override
    public void afterMeleeHit(IToolStackView tool, ModifierEntry modifier, ToolAttackContext context, float damageDealt) {
        if(damageDealt >= 100){
            context.getAttacker().addEffect(new MobEffectInstance(MobeffectRegistry.DREAM_POWER.get(),140,modifier.getLevel() - 1));
        }
    }
}
